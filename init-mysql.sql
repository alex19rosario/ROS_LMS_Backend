CREATE OR REPLACE VIEW MEMBER_STATUS_VIEW AS
SELECT
    m.MEMBER_ID,
    m.FIRST_NAME,
    m.LAST_NAME,
    CASE
        WHEN EXISTS (
            SELECT 1
            FROM LOANS l
            WHERE l.MEMBER_ID = m.MEMBER_ID AND l.STATUS_ID = 3 -- OVERDUE
        ) THEN 'OVERDUE'

        WHEN EXISTS (
            SELECT 1
            FROM LOANS l
            WHERE l.MEMBER_ID = m.MEMBER_ID AND l.STATUS_ID = 1 -- LOANED
        ) THEN 'HAS-LOAN'

        ELSE 'ELIGIBLE'
    END AS MEMBER_STATUS
FROM MEMBERS m;


