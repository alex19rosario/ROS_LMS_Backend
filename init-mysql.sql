-- Create database
CREATE DATABASE IF NOT EXISTS `ros-lms-db`;
USE `ros-lms-db`;

-- Drop tables if they exist (in reverse order of creation due to FK constraints)
DROP TABLE IF EXISTS LOANS;
DROP TABLE IF EXISTS LOAN_STATUSES;
DROP TABLE IF EXISTS STAFFS;
DROP TABLE IF EXISTS MEMBERS;
DROP TABLE IF EXISTS USERS_AUTHORITIES;
DROP TABLE IF EXISTS USERS;
DROP TABLE IF EXISTS BOOKS_GENRES;
DROP TABLE IF EXISTS BOOKS_AUTHORS;
DROP TABLE IF EXISTS BOOKS;
DROP TABLE IF EXISTS GENRE_TYPE;
DROP TABLE IF EXISTS AUTHORS;
DROP TABLE IF EXISTS AUTHORITY_TYPE;
DROP PROCEDURE IF EXISTS GENERATE_LOG;

-- Create tables with named constraints
CREATE TABLE GENRE_TYPE (
    GENRE_ID BIGINT AUTO_INCREMENT,
    LABEL VARCHAR(50),
    CONSTRAINT GENRE_ID_PK PRIMARY KEY (GENRE_ID),
    CONSTRAINT GENRE_LABEL_UK UNIQUE (LABEL)
);

CREATE TABLE BOOKS (
    BOOK_ID BIGINT AUTO_INCREMENT,
    ISBN VARCHAR(13),
    TITLE VARCHAR(50) NOT NULL,
    IS_AVAILABLE CHAR(1),
    COVER_IMAGE_PATH VARCHAR(200),
    CREATED_AT DATETIME DEFAULT NULL,
    UPDATED_AT DATETIME DEFAULT NULL,
    CONSTRAINT BOOK_ID_PK PRIMARY KEY (BOOK_ID),
    CONSTRAINT BOOK_ISBN_UK UNIQUE (ISBN),
    CONSTRAINT BOOK_AVAILABLE_CK CHECK (IS_AVAILABLE IN ('Y', 'N'))
);

CREATE TABLE BOOKS_GENRES (
    BOOK_ID BIGINT,
    GENRE_ID BIGINT,
    CONSTRAINT BOOKGENRE_PK PRIMARY KEY (BOOK_ID, GENRE_ID),
    CONSTRAINT BOOKGENRE_BOOK_FK FOREIGN KEY (BOOK_ID) REFERENCES BOOKS(BOOK_ID),
    CONSTRAINT BOOKGENRE_GENRE_FK FOREIGN KEY (GENRE_ID) REFERENCES GENRE_TYPE(GENRE_ID)
);

CREATE TABLE AUTHORS (
    AUTHOR_ID BIGINT AUTO_INCREMENT,
    FIRST_NAME VARCHAR(50) NOT NULL,
    MIDDLE_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50) NOT NULL,
    CONSTRAINT AUTHOR_ID_PK PRIMARY KEY (AUTHOR_ID),
    CONSTRAINT AUTHOR_NAME_UK UNIQUE (FIRST_NAME, MIDDLE_NAME, LAST_NAME)
);

CREATE TABLE BOOKS_AUTHORS (
    BOOK_ID BIGINT,
    AUTHOR_ID BIGINT,
    CONSTRAINT BOOKAUTHOR_PK PRIMARY KEY (BOOK_ID, AUTHOR_ID),
    CONSTRAINT BOOKAUTHOR_BOOK_FK FOREIGN KEY (BOOK_ID) REFERENCES BOOKS(BOOK_ID),
    CONSTRAINT BOOKAUTHOR_AUTHOR_FK FOREIGN KEY (AUTHOR_ID) REFERENCES AUTHORS(AUTHOR_ID)
);

CREATE TABLE AUTHORITY_TYPE (
    AUTHORITY_TYPE_ID INT AUTO_INCREMENT,
    LABEL VARCHAR(128),
    CONSTRAINT AUTHORITY_TYPE_ID_PK PRIMARY KEY (AUTHORITY_TYPE_ID),
    CONSTRAINT AUTHORITY_TYPE_LABEL_UK UNIQUE (LABEL)
);

CREATE TABLE USERS (
    USER_ID BIGINT AUTO_INCREMENT,
    USERNAME VARCHAR(128),
    EMAIL VARCHAR(128),
    PASSWORD VARCHAR(128) NOT NULL,
    ENABLED CHAR(1) NOT NULL,
    CONSTRAINT USER_ID_PK PRIMARY KEY (USER_ID),
    CONSTRAINT USER_NAME_UK UNIQUE (USERNAME),
    CONSTRAINT USER_EMAIL_UK UNIQUE (EMAIL),
    CONSTRAINT USER_ENABLED_CK CHECK (ENABLED IN ('Y','N'))
);

CREATE TABLE USERS_AUTHORITIES (
    USER_ID BIGINT NOT NULL,
    AUTHORITY_TYPE_ID INT NOT NULL,
    CONSTRAINT USERS_AUTHORITIES_PK PRIMARY KEY (USER_ID, AUTHORITY_TYPE_ID),
    CONSTRAINT USERS_AUTHORITIES_USER_FK FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID),
    CONSTRAINT USERS_AUTHORITIES_AUTHORITY_FK FOREIGN KEY (AUTHORITY_TYPE_ID) REFERENCES AUTHORITY_TYPE (AUTHORITY_TYPE_ID)
);

CREATE TABLE MEMBERS (
    MEMBER_ID BIGINT AUTO_INCREMENT,
    USER_ID BIGINT NOT NULL,
    GOVERNMENT_ID VARCHAR(15),
    FIRST_NAME VARCHAR(50) NOT NULL,
    MIDDLE_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50) NOT NULL,
    PHONE VARCHAR(20) NOT NULL,
    DATE_OF_BIRTH DATE,
    SEX CHAR(1),
    CREATED_AT DATETIME DEFAULT NULL,
    UPDATED_AT DATETIME DEFAULT NULL,
    CONSTRAINT MEMBER_ID_PK PRIMARY KEY (MEMBER_ID),
    CONSTRAINT MEMBER_GOV_ID_UK UNIQUE (GOVERNMENT_ID),
    CONSTRAINT MEMBER_SEX_CK CHECK (SEX IN ('M', 'F')),
    CONSTRAINT MEMBER_USER_FK FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT MEMBER_USER_UK UNIQUE (USER_ID)
);

CREATE TABLE STAFFS (
    STAFF_ID BIGINT AUTO_INCREMENT,
    USER_ID BIGINT NOT NULL,
    GOVERNMENT_ID VARCHAR(15),
    FIRST_NAME VARCHAR(50) NOT NULL,
    MIDDLE_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50) NOT NULL,
    PHONE VARCHAR(20) NOT NULL,
    SEX CHAR(1),
    CREATED_AT DATETIME DEFAULT NULL,
    UPDATED_AT DATETIME DEFAULT NULL,
    CONSTRAINT STAFF_ID_PK PRIMARY KEY (STAFF_ID),
    CONSTRAINT STAFF_GOV_ID_UK UNIQUE (GOVERNMENT_ID),
    CONSTRAINT STAFF_SEX_CK CHECK (SEX IN ('M', 'F')),
    CONSTRAINT STAFF_USER_FK FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT STAFF_USER_UK UNIQUE (USER_ID)
);

CREATE TABLE LOAN_STATUSES (
    STATUS_ID BIGINT AUTO_INCREMENT,
    CODE VARCHAR(50),
    CONSTRAINT LOAN_STATUS_ID_PK PRIMARY KEY (STATUS_ID),
    CONSTRAINT LOAN_STATUS_CODE_UK UNIQUE (CODE)
);

CREATE TABLE LOANS (
    LOAN_ID BIGINT AUTO_INCREMENT,
    MEMBER_ID BIGINT,
    BOOK_ID BIGINT,
    LOAN_DATE DATETIME NOT NULL,
    DUE_DATE DATETIME NOT NULL,
    RETURN_DATE DATETIME,
    STATUS_ID BIGINT,
    STAFF_ID BIGINT,
    CREATED_AT DATETIME DEFAULT NULL,
    UPDATED_AT DATETIME DEFAULT NULL,
    CONSTRAINT LOAN_ID_PK PRIMARY KEY (LOAN_ID),
    CONSTRAINT LOAN_MEMBER_FK FOREIGN KEY (MEMBER_ID) REFERENCES MEMBERS(MEMBER_ID),
    CONSTRAINT LOAN_BOOK_FK FOREIGN KEY (BOOK_ID) REFERENCES BOOKS(BOOK_ID),
    CONSTRAINT LOAN_STATUS_FK FOREIGN KEY (STATUS_ID) REFERENCES LOAN_STATUSES(STATUS_ID),
    CONSTRAINT LOAN_STAFF_ID FOREIGN KEY (STAFF_ID) REFERENCES STAFFS(STAFF_ID)
);

