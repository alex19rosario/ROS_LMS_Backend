DELIMITER //
CREATE PROCEDURE GENERATE_LOG(
    IN P_DESCRIPTION VARCHAR(300),
    IN P_ACTION_TYPE VARCHAR(50),
    IN P_STAFF_USERNAME VARCHAR(128),
    IN P_MEMBER_USERNAME VARCHAR(128),
    IN P_BOOK_ISBN VARCHAR(13),
    IN P_LOAN_ID BIGINT
)
BEGIN
    INSERT INTO LOGS (
        LOG_DESCRIPTION,
        LOG_DATE,
        ACTION_TYPE,
        STAFF_USERNAME,
        MEMBER_USERNAME,
        BOOK_ISBN,
        LOAN_ID
    ) VALUES (
        P_DESCRIPTION,
        NOW(),
        P_ACTION_TYPE,
        P_STAFF_USERNAME,
        P_MEMBER_USERNAME,
        P_BOOK_ISBN,
        P_LOAN_ID
    );
END //
DELIMITER ;

