-- Create database
CREATE DATABASE IF NOT EXISTS `ros-lms-db`;
USE `ros-lms-db`;

-- Drop tables if they exist (in reverse order of creation due to FK constraints)
DROP TABLE IF EXISTS LOGS;
DROP TABLE IF EXISTS LOANS;
DROP TABLE IF EXISTS STATUS;
DROP TABLE IF EXISTS STAFFS;
DROP TABLE IF EXISTS AUTHORITIES;
DROP TABLE IF EXISTS AUTHORITY_TYPE;
DROP TABLE IF EXISTS MEMBERS;
DROP TABLE IF EXISTS USERS;
DROP TABLE IF EXISTS BOOKS_AUTHORS;
DROP TABLE IF EXISTS BOOKS_GENRES;
DROP TABLE IF EXISTS BOOKS;
DROP TABLE IF EXISTS GENRES;
DROP TABLE IF EXISTS AUTHORS;
DROP PROCEDURE IF EXISTS GENERATE_LOG;

-- Create tables with named constraints
CREATE TABLE GENRES (
    GENRE_ID INT AUTO_INCREMENT,
    DESCRIPTION VARCHAR(50),
    CONSTRAINT GENRE_ID_PK PRIMARY KEY (GENRE_ID),
    CONSTRAINT GENRE_DESC_UK UNIQUE (DESCRIPTION)
);

CREATE TABLE BOOKS (
    BOOK_ID INT AUTO_INCREMENT,
    ISBN BIGINT,
    TITLE VARCHAR(50) NOT NULL,
    IS_AVAILABLE CHAR(1),
    COVER_IMAGE_PATH VARCHAR(200),
    CONSTRAINT BOOK_ID_PK PRIMARY KEY (BOOK_ID),
    CONSTRAINT BOOK_ISBN_UK UNIQUE (ISBN),
    CONSTRAINT BOOK_AVAILABLE_CK CHECK (IS_AVAILABLE IN ('Y', 'N'))
);

CREATE TABLE BOOKS_GENRES (
    BOOK_ID INT,
    GENRE_ID INT,
    CONSTRAINT BOOKGENRE_PK PRIMARY KEY (BOOK_ID, GENRE_ID),
    CONSTRAINT BOOKGENRE_BOOK_FK FOREIGN KEY (BOOK_ID) REFERENCES BOOKS(BOOK_ID),
    CONSTRAINT BOOKGENRE_GENRE_FK FOREIGN KEY (GENRE_ID) REFERENCES GENRES(GENRE_ID)
);

CREATE TABLE AUTHORS (
    AUTHOR_ID INT AUTO_INCREMENT,
    FIRST_NAME VARCHAR(50) NOT NULL,
    MIDDLE_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50) NOT NULL,
    CONSTRAINT AUTHOR_ID_PK PRIMARY KEY (AUTHOR_ID),
    CONSTRAINT AUTHOR_NAME_UK UNIQUE (FIRST_NAME, MIDDLE_NAME, LAST_NAME)
);

CREATE TABLE BOOKS_AUTHORS (
    BOOK_ID INT,
    AUTHOR_ID INT,
    CONSTRAINT BOOKAUTHOR_PK PRIMARY KEY (BOOK_ID, AUTHOR_ID),
    CONSTRAINT BOOKAUTHOR_BOOK_FK FOREIGN KEY (BOOK_ID) REFERENCES BOOKS(BOOK_ID),
    CONSTRAINT BOOKAUTHOR_AUTHOR_FK FOREIGN KEY (AUTHOR_ID) REFERENCES AUTHORS(AUTHOR_ID)
);

CREATE TABLE AUTHORITY_TYPE (
    TYPE_DESCRIPTION VARCHAR(128),
    CONSTRAINT AUTHORITY_TYPE_UK UNIQUE (TYPE_DESCRIPTION)
);

CREATE TABLE USERS (
    USERNAME VARCHAR(128),
    PASSWORD VARCHAR(128) NOT NULL,
    ENABLED CHAR(1) NOT NULL,
    CONSTRAINT USER_ID_PK PRIMARY KEY (USERNAME),
    CONSTRAINT USER_ENABLED_CK CHECK (ENABLED IN ('Y','N'))
);

CREATE TABLE AUTHORITIES (
    USERNAME VARCHAR(128) NOT NULL,
    AUTHORITY VARCHAR(128) NOT NULL,
    CONSTRAINT AUTHORITIES_UNIQUE UNIQUE (USERNAME, AUTHORITY),
    CONSTRAINT AUTHORITIES_USERNAME_FK FOREIGN KEY (USERNAME) REFERENCES USERS (USERNAME),
    CONSTRAINT AUTHORITIES_AUTHORITY_FK FOREIGN KEY (AUTHORITY) REFERENCES AUTHORITY_TYPE (TYPE_DESCRIPTION)
);

CREATE TABLE MEMBERS (
    MEMBER_ID INT AUTO_INCREMENT,
    GOVERNMENT_ID VARCHAR(15),
    FIRST_NAME VARCHAR(50) NOT NULL,
    MIDDLE_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50) NOT NULL,
    PHONE VARCHAR(20) NOT NULL,
    DATE_OF_BIRTH DATE,
    SEX CHAR(1),
    EMAIL VARCHAR(65),
    USERNAME VARCHAR(128),
    CONSTRAINT MEMBER_ID_PK PRIMARY KEY (MEMBER_ID),
    CONSTRAINT MEMBER_GOVERNMENTID_UK UNIQUE (GOVERNMENT_ID),
    CONSTRAINT MEMBER_SEX_CK CHECK (SEX IN ('M', 'F')),
    CONSTRAINT MEMBER_EMAIL_UK UNIQUE (EMAIL),
    CONSTRAINT MEMBER_USERNAME_FK FOREIGN KEY (USERNAME) REFERENCES USERS(USERNAME)
);

CREATE TABLE STAFFS (
    STAFF_ID INT AUTO_INCREMENT,
    GOVERNMENT_ID INT,
    FIRST_NAME VARCHAR(50) NOT NULL,
    MIDDLE_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50) NOT NULL,
    PHONE VARCHAR(20) NOT NULL,
    SEX CHAR(1),
    EMAIL VARCHAR(65),
    USERNAME VARCHAR(128),
    CONSTRAINT STAFF_ID_PK PRIMARY KEY (STAFF_ID),
    CONSTRAINT STAFF_ID_UK UNIQUE (GOVERNMENT_ID),
    CONSTRAINT STAFF_SEX_CK CHECK (SEX IN ('M', 'F')),
    CONSTRAINT STAFF_EMAIL_UK UNIQUE (EMAIL),
    CONSTRAINT STAFF_USERNAME_FK FOREIGN KEY (USERNAME) REFERENCES USERS(USERNAME)
);

CREATE TABLE STATUS (
    STATUS_ID INT AUTO_INCREMENT,
    DESCRIPTION VARCHAR(50),
    CONSTRAINT STATUS_ID_PK PRIMARY KEY (STATUS_ID),
    CONSTRAINT STATUS_DESC_UK UNIQUE (DESCRIPTION)
);

CREATE TABLE LOANS (
    LOAN_ID INT AUTO_INCREMENT,
    MEMBER_ID INT,
    BOOK_ID INT,
    LOAN_DATE DATETIME NOT NULL,
    DUE_DATE DATETIME NOT NULL,
    RETURN_DATE DATETIME,
    STATUS_ID INT,
    STAFF_ID INT,
    CONSTRAINT LOAN_ID_PK PRIMARY KEY (LOAN_ID),
    CONSTRAINT LOAN_MEMBER_FK FOREIGN KEY (MEMBER_ID) REFERENCES MEMBERS(MEMBER_ID),
    CONSTRAINT LOAN_BOOK_FK FOREIGN KEY (BOOK_ID) REFERENCES BOOKS(BOOK_ID),
    CONSTRAINT LOAN_STATUS_FK FOREIGN KEY (STATUS_ID) REFERENCES STATUS(STATUS_ID),
    CONSTRAINT LOAN_STAFF_ID FOREIGN KEY (STAFF_ID) REFERENCES STAFFS(STAFF_ID)
);

CREATE TABLE LOGS (
    LOG_ID INT AUTO_INCREMENT,
    LOG_DESCRIPTION VARCHAR(300),
    LOG_DATE DATETIME NOT NULL,
    ACTION_TYPE VARCHAR(50),
    CONSTRAINT LOG_ID_PK PRIMARY KEY (LOG_ID),
    CONSTRAINT LOG_ACTION_CK CHECK (ACTION_TYPE IN
        ('NEW BOOK WAS ADDED',
        'A BOOK WAS BORROWED',
        'A BOOK WAS RETURNED',
        'OVERDUE',
        'NEW MEMBER WAS ADDED',
        'NEW STAFF WAS ADDED',
        'ERROR'))
);

-- MySQL stored procedure to replace Oracle's GENERATE_LOG
DELIMITER //
CREATE PROCEDURE GENERATE_LOG(
    IN P_DESCRIPTION VARCHAR(300),
    IN P_ACTION_TYPE VARCHAR(50)
)
BEGIN
    INSERT INTO LOGS (LOG_DESCRIPTION, LOG_DATE, ACTION_TYPE)
    VALUES (P_DESCRIPTION, NOW(), P_ACTION_TYPE);
END //
DELIMITER ;

